#!/usr/bin/env python3
import os
import re
import sys

MAPPING = re.compile(r'@(Get|Post|Put|Delete|Patch|Request)Mapping\s*(\((?P<args>[^)]*)\))?')
CONTROLLER = re.compile(r'@(RestController|Controller)\b')
CLASS_DECL = re.compile(r'\b(class|interface|record)\s+\w+')
STRING = re.compile(r'"([^"]*)"')
METHOD_ARG = re.compile(r'RequestMethod\.(\w+)')
SKIPPED_DIRS = {'build', 'out', 'node_modules'}


def mapping_paths(args):
    if not args:
        return ['']
    named = re.search(r'\b(path|value)\s*=\s*(\{[^}]*\}|"[^"]*")', args)
    source = named.group(2) if named else args.split('method')[0]
    return STRING.findall(source) or ['']


def endpoints(source):
    if not CONTROLLER.search(source):
        return []
    class_start = CLASS_DECL.search(source).start()
    prefixes = ['']
    found = []
    for match in MAPPING.finditer(source):
        kind, args = match.group(1), match.group('args')
        if match.start() < class_start:
            if kind == 'Request':
                prefixes = mapping_paths(args)
            continue
        methods = [kind.upper()] if kind != 'Request' else (METHOD_ARG.findall(args or '') or ['ANY'])
        for prefix in prefixes:
            for path in mapping_paths(args):
                for method in methods:
                    found.append((method, '/' + '/'.join(p for p in (prefix + '/' + path).split('/') if p)))
    return found


def service_of(path):
    parts = path.split(os.sep)
    return parts[parts.index('src') - 1]


def collect(root):
    rows = set()
    for directory, subdirs, files in os.walk(root):
        subdirs[:] = [d for d in subdirs if not d.startswith('.') and d not in SKIPPED_DIRS]
        if f'{os.sep}src{os.sep}main{os.sep}java' not in directory + os.sep:
            continue
        for name in files:
            if name.endswith('.java'):
                path = os.path.join(directory, name)
                with open(path, encoding='utf-8') as handle:
                    for method, url in endpoints(handle.read()):
                        rows.add((service_of(os.path.relpath(path, root)), method, url))
    return sorted(rows)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else '.'
    rows = collect(root)
    print('# API contract')
    print()
    print('Generated by `python3 scripts/extract-endpoints.py <root>`. Regenerate it and diff against this file to prove the HTTP surface is unchanged.')
    print()
    print('| Service | Method | Path |')
    print('| --- | --- | --- |')
    for service, method, url in rows:
        print(f'| {service} | {method} | `{url}` |')
    print()
    print(f'{len(rows)} endpoints.')


if __name__ == '__main__':
    main()
