package com.jaypay.messaging;

import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.json.JsonMapper;
import org.axonframework.springboot.autoconfig.ObjectMapperAutoConfiguration;
import org.springframework.boot.autoconfigure.AutoConfiguration;
import org.springframework.boot.autoconfigure.condition.ConditionalOnClass;
import org.springframework.context.annotation.Bean;

@AutoConfiguration(before = ObjectMapperAutoConfiguration.class)
@ConditionalOnClass(ObjectMapperAutoConfiguration.class)
public class MessageJsonAutoConfiguration {

    @Bean
    public ObjectMapper defaultAxonObjectMapper() {
        return JsonMapper.builder()
                .findAndAddModules()
                .disable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES)
                .build();
    }
}
